                @asynccontextmanager
                async def dashboard_session():
                    yield AsyncSessionAdapter(write)
                gateway = AutoTagGateway(read)
                result = AutoTagResult(problem_id=1, primary_tag_id=1, secondary_tag_ids=[],
                                       bloom_group_id=4, reasoning="Test kết nối")
